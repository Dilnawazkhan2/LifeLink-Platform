// Writes supabase/deploy/lifelink_schema.sql: every migration in order + the
// reviewed reference data (partner hospitals). Paste it into the Supabase SQL
// editor of a NEW, EMPTY project, or use `npx supabase db push` instead.
// Never includes seeds/dev_demo.sql (demo accounts are for local development only).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const migDir = path.join(root, 'supabase/migrations');
const files = fs.readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort();
const parts = [
  '-- ============================================================================',
  '-- LifeLink Platform — complete database schema (generated by scripts/bundle-sql.mjs)',
  `-- Generated: ${new Date().toISOString()}`,
  '-- Run ONCE in the Supabase SQL editor of a new project (Database → SQL Editor → New query → paste → Run).',
  '-- Contains: ' + files.join(', ') + ', seeds/reference.sql',
  '-- ============================================================================',
  '',
];
for (const f of files) parts.push(`-- >>> ${f}`, fs.readFileSync(path.join(migDir, f), 'utf8').trim(), '');
parts.push('-- >>> seeds/reference.sql (partner hospitals + starting inventory — review the figures)', fs.readFileSync(path.join(root, 'supabase/seeds/reference.sql'), 'utf8').trim(), '');
const out = path.join(root, 'supabase/deploy/lifelink_schema.sql');
fs.writeFileSync(out, parts.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)} (${files.length} migrations + reference data)`);
